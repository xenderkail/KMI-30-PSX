export function calculatePivots(high: number, low: number, close: number) {
  const pp = Number(((high + low + close) / 3).toFixed(2));
  const r1 = Number((2 * pp - low).toFixed(2));
  const s1 = Number((2 * pp - high).toFixed(2));
  const r2 = Number((pp + (high - low)).toFixed(2));
  const s2 = Number((pp - (high - low)).toFixed(2));
  const r3 = Number((high + 2 * (pp - low)).toFixed(2));
  const s3 = Number((low - 2 * (high - pp)).toFixed(2));
  return { pp, r1, r2, r3, s1, s2, s3 };
}

/**
 * Deterministic pseudo-random number based on a seed string
 */
function seededRandom(seedStr: string, index: number): number {
  let h = 0x811c9dc5;
  const s = `${seedStr}_${index}`;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h += (h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24);
  }
  return (h >>> 0) / 4294967296;
}

/**
 * Generate 30 distinct daily candles with stock-specific trajectory & realistic volatility
 */
export function generateStockHistory(
  symbol: string,
  currentPrice: number,
  baseVol: number,
  pattern: 'ASCENDING_CHANNEL' | 'CUP_AND_HANDLE' | 'BREAKOUT_RETEST' | 'CONSOLIDATION_BOX' | 'BULL_FLAG' | 'DOUBLE_BOTTOM' = 'ASCENDING_CHANNEL'
): Candle[] {
  const days = 30;
  const candles: Candle[] = [];

  // Generate 30 trading days ending Friday 9 Oct 2026 (11 Oct 2026 is Sunday)
  const endDate = new Date(2026, 9, 9);
  const dates: string[] = [];
  let d = new Date(endDate);
  while (dates.length < days) {
    const dayOfWeek = d.getDay();
    if (dayOfWeek !== 0 && dayOfWeek !== 6) {
      const monthNames = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
      dates.unshift(`${d.getDate()} ${monthNames[d.getMonth()]}`);
    }
    d.setDate(d.getDate() - 1);
  }

  // Define unique trajectory curves for different patterns
  const trajectory: number[] = [];
  for (let i = 0; i < days; i++) {
    const progress = i / (days - 1); // 0.0 to 1.0
    const rand = (seededRandom(symbol, i) - 0.5) * 0.025; // small noise

    let multiplier = 1.0;
    switch (pattern) {
      case 'ASCENDING_CHANNEL':
        // Steady higher lows, ending at currentPrice (e.g. DGKC, SAZEW)
        multiplier = 0.82 + 0.18 * progress + Math.sin(progress * Math.PI * 3) * 0.02 + rand;
        break;
      case 'CUP_AND_HANDLE':
        // Rounded dip in middle, sharp handle recovery (e.g. MEBL, FFC)
        multiplier = 0.95 - 0.12 * Math.sin(progress * Math.PI) + 0.05 * progress + rand;
        break;
      case 'BREAKOUT_RETEST':
        // Flat base until day 22, breakout surge, retest bounce (e.g. LUCK, FCCL)
        if (progress < 0.65) {
          multiplier = 0.88 + progress * 0.04 + rand;
        } else if (progress < 0.85) {
          multiplier = 0.92 + (progress - 0.65) * 0.45 + rand;
        } else {
          multiplier = 0.97 + (progress - 0.85) * 0.20 + rand;
        }
        break;
      case 'CONSOLIDATION_BOX':
        // Tight oscillating range between support and resistance (e.g. LOTCHEM at 26, ILP)
        multiplier = 0.96 + Math.sin(progress * Math.PI * 4) * 0.035 + rand;
        break;
      case 'BULL_FLAG':
        // Early surge then downward drifting flag, then final bounce (e.g. SYS, MARI)
        if (progress < 0.4) {
          multiplier = 0.84 + progress * 0.35 + rand;
        } else if (progress < 0.8) {
          multiplier = 0.98 - (progress - 0.4) * 0.08 + rand;
        } else {
          multiplier = 0.95 + (progress - 0.8) * 0.25 + rand;
        }
        break;
      case 'DOUBLE_BOTTOM':
        // W bottom pattern (e.g. OGDC, PPL)
        multiplier = 0.90 + 0.08 * Math.cos(progress * Math.PI * 3.5) + progress * 0.08 + rand;
        break;
      default:
        multiplier = 0.88 + 0.12 * progress + rand;
    }
    trajectory.push(multiplier);
  }

  // Anchor the very last day exactly to currentPrice
  const lastMult = trajectory[days - 1];

  for (let i = 0; i < days; i++) {
    const isLast = i === days - 1;
    // Normalized close so day 30 is exactly currentPrice
    const close = isLast ? currentPrice : Number(((trajectory[i] / lastMult) * currentPrice).toFixed(2));
    const noise = (seededRandom(symbol, i + 100) - 0.5) * 0.015;
    const open = isLast
      ? Number((close * 0.992).toFixed(2))
      : Number((close * (1 + noise)).toFixed(2));
    const high = Number((Math.max(open, close) * (1 + seededRandom(symbol, i + 200) * 0.018)).toFixed(2));
    const low = Number((Math.min(open, close) * (1 - seededRandom(symbol, i + 300) * 0.016)).toFixed(2));
    const volNoise = 0.7 + seededRandom(symbol, i + 400) * 0.6;
    const volume = Math.floor(baseVol * volNoise);

    candles.push({
      date: dates[i],
      open,
      high,
      low,
      close,
      volume,
    });
  }

  return candles;
}

/**
 * Calculate true mathematical EMA series
 */
export function calculateEmaSeries(candles: Candle[], period: number): number[] {
  if (candles.length === 0) return [];
  const k = 2 / (period + 1);
  const emaValues: number[] = [];
  let ema = candles[0].close;
  emaValues.push(ema);

  for (let i = 1; i < candles.length; i++) {
    ema = candles[i].close * k + ema * (1 - k);
    emaValues.push(Number(ema.toFixed(2)));
  }
  return emaValues;
}

export function generateOrderBook(price: number, baseVol: number): OrderBook {
  const tick = price > 200 ? 0.25 : price > 50 ? 0.10 : 0.05;
  const bids: OrderBookLevel[] = [];
  const asks: OrderBookLevel[] = [];

  let cumBidShares = 0;
  for (let i = 1; i <= 5; i++) {
    const bidPrice = Number((price - i * tick).toFixed(2));
    const shares = Math.floor((baseVol * 0.008) * (1 + Math.sin(i) * 0.3) + (6 - i) * 8000);
    const count = 12 + i * 7;
    cumBidShares += shares;
    const totalPKR = Number(((cumBidShares * bidPrice) / 1_000_000).toFixed(2));
    bids.push({
      price: bidPrice,
      orders: count,
      shares,
      cumulativeShares: cumBidShares,
      totalValueMillion: totalPKR,
    });
  }

  let cumAskShares = 0;
  for (let i = 1; i <= 5; i++) {
    const askPrice = Number((price + i * tick).toFixed(2));
    const shares = Math.floor((baseVol * 0.0075) * (1 + Math.cos(i) * 0.3) + (6 - i) * 7500);
    const count = 10 + i * 6;
    cumAskShares += shares;
    const totalPKR = Number(((cumAskShares * askPrice) / 1_000_000).toFixed(2));
    asks.push({
      price: askPrice,
      orders: count,
      shares,
      cumulativeShares: cumAskShares,
      totalValueMillion: totalPKR,
    });
  }

  const totalDepth = cumBidShares + cumAskShares;
  const buyerPct = Math.round((cumBidShares / totalDepth) * 100);
  const sellerPct = 100 - buyerPct;
  const spreadPKR = Number((tick * 2).toFixed(2));
  const spreadBps = Number(((spreadPKR / price) * 10000).toFixed(1));

  const recentBlocks: BlockOrder[] = [
    {
      id: 'blk-1',
      time: '11:28:44',
      type: 'BUY',
      price: Number((price - tick).toFixed(2)),
      shares: Math.floor(baseVol * 0.018 + 50000),
      institutionType: 'MUTUAL_FUND',
      valuePKRMillion: Number(((price * 75000) / 1_000_000).toFixed(2)),
    },
    {
      id: 'blk-2',
      time: '10:52:19',
      type: 'BUY',
      price: Number((price - 2 * tick).toFixed(2)),
      shares: Math.floor(baseVol * 0.012 + 35000),
      institutionType: 'MUTUAL_FUND',
      valuePKRMillion: Number(((price * 52000) / 1_000_000).toFixed(2)),
    },
    {
      id: 'blk-3',
      time: '10:14:02',
      type: 'SELL',
      price: Number((price + tick).toFixed(2)),
      shares: Math.floor(baseVol * 0.009 + 25000),
      institutionType: 'FOREIGN_FIPI',
      valuePKRMillion: Number(((price * 38000) / 1_000_000).toFixed(2)),
    },
  ];

  return {
    bids,
    asks,
    buyerImbalancePercent: buyerPct,
    sellerImbalancePercent: sellerPct,
    spreadPKR,
    spreadBps,
    recentBlocks,
  };
}

